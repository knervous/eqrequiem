/**
 * The Ranger's level 1–25 kit.
 *
 * Bow and blade both have to matter, or the class collapses into whichever one is
 * stronger. The kit keeps that honest by making them answer different ranges: archery
 * opens and controls, melee finishes, and snare is what converts distance into time.
 *
 * Vigor pays for the physical half and a small mana pool for the primal half. The mana
 * pool is deliberately too small to make a Ranger a caster and exactly big enough to
 * make Snaring Thorn a real decision.
 */

